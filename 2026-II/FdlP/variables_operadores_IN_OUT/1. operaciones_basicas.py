# Pide dos números y muestra suma, resta, multiplicación,
# división, residuo y división entera.
# leer 2 numeros enteros
a=int(input("Ingrese a: "))
b=int(input("Ingrese b: "))

# calcular y mostrar resultados
print("Suma: ",a+b)
print("Resta: ",a-b)
print("Multiplicación: ",a*b)
print("División: ",a/b)
print("Residuo: ",a%b)
print("División entera: ",a//b)

